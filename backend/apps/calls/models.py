"""Call history and client-reported call quality metrics."""

from __future__ import annotations

from typing import ClassVar

from django.conf import settings
from django.db import models
from django.db.models import Q
from django.utils import timezone


class CallMedia(models.TextChoices):
    AUDIO = "audio", "Audio"
    VIDEO = "video", "Video"


class CallState(models.TextChoices):
    RINGING = "ringing", "Ringing"
    ACTIVE = "active", "Active"
    ENDED = "ended", "Ended"


class EndReason(models.TextChoices):
    COMPLETED = "completed", "Completed"
    MISSED = "missed", "Missed"
    DECLINED = "declined", "Declined"
    CANCELLED = "cancelled", "Cancelled"
    FAILED = "failed", "Failed"
    BUSY = "busy", "Busy"
    ANSWERED_ELSEWHERE = "answered_elsewhere", "Answered elsewhere"
    TIMEOUT = "timeout", "Timeout"


class Call(models.Model):
    # Generated by the caller's client so that the push and the socket agree on it.
    id = models.UUIDField(primary_key=True, editable=False)
    conversation = models.ForeignKey(
        "chat.Conversation", on_delete=models.CASCADE, related_name="calls"
    )
    caller = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="calls_made"
    )
    callee = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="calls_received"
    )
    media = models.CharField(max_length=8, choices=CallMedia.choices)
    state = models.CharField(max_length=8, choices=CallState.choices, default=CallState.RINGING)
    caller_session = models.ForeignKey(
        "accounts.Session", null=True, blank=True, on_delete=models.SET_NULL, related_name="+"
    )
    callee_session = models.ForeignKey(
        "accounts.Session", null=True, blank=True, on_delete=models.SET_NULL, related_name="+"
    )
    created_at = models.DateTimeField(default=timezone.now, editable=False)
    answered_at = models.DateTimeField(null=True, blank=True)
    ended_at = models.DateTimeField(null=True, blank=True)
    end_reason = models.CharField(max_length=24, choices=EndReason.choices, blank=True, default="")

    class Meta:
        indexes: ClassVar = [
            models.Index(fields=["caller", "-created_at", "-id"], name="call_caller_idx"),
            models.Index(fields=["callee", "-created_at", "-id"], name="call_callee_idx"),
            models.Index(
                fields=["state", "created_at"],
                name="call_live_idx",
                condition=Q(state__in=["ringing", "active"]),
            ),
        ]

    def __str__(self) -> str:
        return f"call {self.id} ({self.state})"

    @property
    def duration_sec(self) -> int:
        if self.answered_at and self.ended_at:
            return max(0, int((self.ended_at - self.answered_at).total_seconds()))
        return 0


class CallMetrics(models.Model):
    """Quality summary submitted by each participant after a call."""

    id = models.BigAutoField(primary_key=True)
    call = models.ForeignKey(Call, on_delete=models.CASCADE, related_name="metrics")
    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="+")
    rtt_ms_avg = models.FloatField(null=True, blank=True)
    jitter_ms_avg = models.FloatField(null=True, blank=True)
    packet_loss_pct_avg = models.FloatField(null=True, blank=True)
    bitrate_kbps_avg_up = models.FloatField(null=True, blank=True)
    bitrate_kbps_avg_down = models.FloatField(null=True, blank=True)
    video_quality_changes = models.IntegerField(null=True, blank=True)
    reconnects = models.IntegerField(null=True, blank=True)
    duration_sec = models.IntegerField(null=True, blank=True)
    network_type = models.CharField(max_length=16, blank=True, default="")
    selected_video_quality = models.CharField(max_length=8, blank=True, default="")
    selected_audio_quality = models.CharField(max_length=8, blank=True, default="")
    created_at = models.DateTimeField(default=timezone.now, editable=False)

    class Meta:
        constraints: ClassVar = [
            models.UniqueConstraint(fields=["call", "user"], name="callmetrics_call_user"),
        ]
        verbose_name_plural = "call metrics"

    def __str__(self) -> str:
        return f"metrics for {self.call_id} by {self.user_id}"
