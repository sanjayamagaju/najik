/**
 * Builds the compact, offline emoji dataset used by the in-app picker from `unicode-emoji-json`
 * (devDependency). Only emoji up to Emoji 13.1 are kept so every glyph renders natively on
 * our minimum OS versions (no tofu boxes). Run: `node scripts/generate-emoji-data.mjs`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const groups = JSON.parse(
  readFileSync(require.resolve('unicode-emoji-json/data-by-group.json'), 'utf8'),
);
const MAX_VERSION = 13.1;

const META = {
  smileys_emotion: { key: 'smileys', title: 'Smileys & Emotion', icon: 'happy-outline' },
  people_body: { key: 'people', title: 'People & Body', icon: 'hand-left-outline' },
  animals_nature: { key: 'nature', title: 'Animals & Nature', icon: 'leaf-outline' },
  food_drink: { key: 'food', title: 'Food & Drink', icon: 'fast-food-outline' },
  travel_places: { key: 'travel', title: 'Travel & Places', icon: 'airplane-outline' },
  activities: { key: 'activities', title: 'Activities', icon: 'football-outline' },
  objects: { key: 'objects', title: 'Objects', icon: 'bulb-outline' },
  symbols: { key: 'symbols', title: 'Symbols', icon: 'heart-outline' },
  flags: { key: 'flags', title: 'Flags', icon: 'flag-outline' },
};

const categories = groups
  .filter((g) => META[g.slug])
  .map((g) => ({
    ...META[g.slug],
    emojis: g.emojis
      .filter((e) => parseFloat(e.emoji_version) <= MAX_VERSION)
      .map((e) => [e.emoji, e.name]),
  }));

const total = categories.reduce((n, c) => n + c.emojis.length, 0);
const body = `// GENERATED by scripts/generate-emoji-data.mjs from unicode-emoji-json — do not edit by hand.
// ${total} emoji (Emoji <= ${MAX_VERSION}).
import type { IconName } from '@/components/Icon';

export interface EmojiCategory {
  key: string;
  title: string;
  icon: IconName;
  /** [emoji, lowercase name] */
  emojis: readonly (readonly [string, string])[];
}

export const EMOJI_CATEGORIES: readonly EmojiCategory[] = ${JSON.stringify(categories)};
`;

const out = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'features',
  'messages',
  'emoji',
  'emojiData.ts',
);
writeFileSync(out, body);
console.log(`wrote ${out} (${total} emoji, ${(body.length / 1024).toFixed(1)} KiB)`);
